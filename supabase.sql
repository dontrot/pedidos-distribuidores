create table if not exists public.products (
  id bigint generated by default as identity primary key,
  brand text not null,
  name text not null,
  price numeric(12,2) not null default 0,
  created_at timestamptz not null default now(),
  unique(brand,name)
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  client text not null,
  status text not null default 'Pendiente' check(status in ('Pendiente','Confirmado','Entregado')),
  total numeric(14,2) not null default 0,
  units integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  brand text not null,
  product_name text not null,
  quantity integer not null,
  unit_price numeric(12,2) not null,
  line_total numeric(14,2) not null
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
-- Acceso público deliberado: cualquier persona con la URL puede leer y modificar.
create policy "public products access" on public.products for all to anon, authenticated using (true) with check (true);
create policy "public orders access" on public.orders for all to anon, authenticated using (true) with check (true);
create policy "public order items access" on public.order_items for all to anon, authenticated using (true) with check (true);
grant usage, select on all sequences in schema public to anon, authenticated;
grant select, insert, update, delete on public.products, public.orders, public.order_items to anon, authenticated;